<!-- =========================================
     HEADER JS (Mobile menu, GSAP indicator,
     Mega menu, Accordion, Search, Bottom bar active)
========================================= -->
<script>
document.addEventListener("DOMContentLoaded", function() {

    /* ==========================================
        MOBILE MENU LOGIC
    ========================================== */
    const menuBtn = document.getElementById("tjMobileMenuBtn");
    const sidebar = document.getElementById("tjMobileSidebar");
    const overlay = document.getElementById("tjMobileOverlay");
    const closeBtn = document.getElementById("tjSidebarClose");

    function openMobileMenu() {
        if (sidebar) sidebar.classList.add("active");
        if (overlay) overlay.classList.add("active");
        document.body.style.overflow = "hidden";
    }

    function closeMobileMenu() {
        if (sidebar) sidebar.classList.remove("active");
        if (overlay) overlay.classList.remove("active");
        document.body.style.overflow = "";
    }

    if (menuBtn) menuBtn.addEventListener("click", openMobileMenu);
    if (closeBtn) closeBtn.addEventListener("click", closeMobileMenu);
    if (overlay) overlay.addEventListener("click", closeMobileMenu);


    /* ==========================================
        GSAP DYNAMIC NAV HOVER/ACTIVE INDICATOR
    ========================================== */
    const navList = document.getElementById("tjNavList");
    const navLinks = document.querySelectorAll(".tj-apparel-nav-link");
    const indicator = document.getElementById("tjNavIndicator");

    if (navList && indicator && navLinks.length > 0 && typeof gsap !== "undefined") {
        const currentPath = window.location.pathname.split("/").pop();

        navLinks.forEach(link => {
            const href = link.getAttribute("href");
            if (href === currentPath || (currentPath === "" && (href === "./" || href === "/"))) {
                navLinks.forEach(l => l.classList.remove("active"));
                link.classList.add("active");
            }
        });

        const activeLink = document.querySelector(".tj-apparel-nav-link.active") || navLinks[0];

        function moveIndicator(link, instant = false) {
            const listRect = navList.getBoundingClientRect();
            const linkRect = link.getBoundingClientRect();
            const left = linkRect.left - listRect.left;
            const width = linkRect.width;

            if (instant) {
                gsap.set(indicator, {
                    x: left,
                    width: width
                });
            } else {
                gsap.to(indicator, {
                    x: left,
                    width: width,
                    duration: 0.4,
                    ease: "power3.out"
                });
            }
        }

        moveIndicator(activeLink, true);

        navLinks.forEach(link => {
            link.addEventListener("mouseenter", function() {
                moveIndicator(this);
            });
        });

        navList.addEventListener("mouseleave", function() {
            const currentActive = document.querySelector(".tj-apparel-nav-link.active") || activeLink;
            moveIndicator(currentActive);
        });
    }


    /* ==========================================
        DESKTOP MEGA MENU (Click support)
    ========================================== */
    const megaItems = document.querySelectorAll('.tj-apparel-nav-item.tj-has-megamenu');

    megaItems.forEach(function(item) {
        const link = item.querySelector('.tj-apparel-nav-link');
        if (!link) return;

        link.addEventListener('click', function(e) {
            const href = link.getAttribute('href');

            if (!href || href === '#' || href === 'javascript:void(0)') {
                e.preventDefault();
            }

            const isOpen = item.classList.contains('menu-open');

            megaItems.forEach(function(other) {
                if (other !== item) other.classList.remove('menu-open');
            });

            if (isOpen) {
                item.classList.remove('menu-open');
            } else {
                item.classList.add('menu-open');
            }
        });
    });


    /* ==========================================
        MOBILE SIDEBAR ACCORDION
    ========================================== */
    const accordions = document.querySelectorAll('.tj-mobile-accordion');

    accordions.forEach(function(acc) {
        const toggle = acc.querySelector('.tj-accordion-toggle');
        const panel = acc.querySelector('.tj-accordion-panel');

        if (!toggle || !panel) return;

        toggle.addEventListener('click', function() {
            const isOpen = acc.classList.contains('is-open');

            accordions.forEach(function(other) {
                if (other !== acc && other.classList.contains('is-open')) {
                    other.classList.remove('is-open');
                    const otherPanel = other.querySelector('.tj-accordion-panel');
                    const otherToggle = other.querySelector('.tj-accordion-toggle');
                    if (otherPanel) otherPanel.style.maxHeight = null;
                    if (otherToggle) otherToggle.setAttribute('aria-expanded', 'false');
                }
            });

            if (isOpen) {
                acc.classList.remove('is-open');
                panel.style.maxHeight = null;
                toggle.setAttribute('aria-expanded', 'false');
            } else {
                acc.classList.add('is-open');
                panel.style.maxHeight = panel.scrollHeight + 'px';
                toggle.setAttribute('aria-expanded', 'true');
            }
        });
    });

    window.addEventListener('resize', function() {
        document.querySelectorAll('.tj-mobile-accordion.is-open .tj-accordion-panel')
            .forEach(function(panel) {
                panel.style.maxHeight = panel.scrollHeight + 'px';
            });
    });


    /* ==========================================
        ADVANCED SLIDE-DOWN SEARCH BAR LOGIC
    ========================================== */
    const searchToggleBtn = document.getElementById("tjSearchToggleBtn");
    const searchCloseBtn = document.getElementById("tjSearchCloseBtn");
    const headerMain = document.getElementById("tjHeaderMain");
    const searchBar = document.getElementById("tjAdvancedSearchBar");
    const searchInput = document.getElementById("tjAdvancedSearchInput");

    function openAdvancedSearch(e) {
        if (e) e.preventDefault();

        if (searchBar && typeof gsap !== "undefined") {
            gsap.set(searchBar, {
                visibility: "visible"
            });

            const tl = gsap.timeline();
            tl.to(headerMain, {
                    y: -60,
                    opacity: 0,
                    duration: 0.3,
                    ease: "power2.in"
                })
                .to(searchBar, {
                    y: 0,
                    opacity: 1,
                    duration: 0.4,
                    ease: "power3.out"
                }, "-=0.1");
        }

        if (searchInput) {
            setTimeout(() => {
                searchInput.focus();
            }, 200);
        }
    }

    function closeAdvancedSearch(e) {
        if (e) e.preventDefault();

        if (searchBar && typeof gsap !== "undefined") {
            const tl = gsap.timeline();
            tl.to(searchBar, {
                    y: -60,
                    opacity: 0,
                    duration: 0.3,
                    ease: "power2.in",
                    onComplete: () => {
                        gsap.set(searchBar, {
                            visibility: "hidden"
                        });
                    }
                })
                .to(headerMain, {
                    y: 0,
                    opacity: 1,
                    duration: 0.4,
                    ease: "power3.out"
                }, "-=0.1");
        }

        if (searchInput) searchInput.value = "";
    }

    if (searchToggleBtn) searchToggleBtn.addEventListener("click", openAdvancedSearch);
    if (searchCloseBtn) searchCloseBtn.addEventListener("click", closeAdvancedSearch);


    /* ==========================================
        MOBILE BOTTOM BAR — ACTIVE LINK DETECTION
    ========================================== */
    (function setBottomBarActive() {
        const bottomItems = document.querySelectorAll('.tj-bottom-item');
        if (!bottomItems.length) return;

        const currentPath = window.location.pathname.split("/").pop().toLowerCase();

        // Reset
        bottomItems.forEach(item => item.classList.remove('active'));

        // Match by href
        let matched = false;
        bottomItems.forEach(item => {
            const href = (item.getAttribute('href') || '').replace('./', '').toLowerCase();

            if (
                (currentPath === '' || currentPath === 'index.php' || currentPath ===
                    'index.html') &&
                (href === '' || href === './' || href === '/' || href === 'index.php')
            ) {
                item.classList.add('active');
                matched = true;
            } else if (href && currentPath && href === currentPath) {
                item.classList.add('active');
                matched = true;
            }
        });

        // Default to Home if nothing matched
        if (!matched) {
            const homeItem = document.querySelector('.tj-bottom-item[href="./"]');
            if (homeItem) homeItem.classList.add('active');
        }
    })();


    /* ==========================================
        GLOBAL ESCAPE & OUTSIDE CLICK HANDLERS
    ========================================== */
    document.addEventListener("keydown", function(event) {
        if (event.key === "Escape") {
            closeMobileMenu();

            megaItems.forEach(function(item) {
                item.classList.remove('menu-open');
            });

            if (searchBar && searchBar.style.visibility === "visible") {
                closeAdvancedSearch();
            }
        }
    });

    document.addEventListener('click', function(e) {
        if (!e.target.closest('.tj-apparel-nav-item.tj-has-megamenu')) {
            megaItems.forEach(function(item) {
                item.classList.remove('menu-open');
            });
        }
    });

});
</script>